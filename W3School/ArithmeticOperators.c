#include <stdio.h>
int main () {
  int x = 6, y = 6, z = 5;
  printf("Addition: %d\n", x+y);
  printf("Substraction: %d\n", x-y);
  printf("Multiplication: %d\n", x*y);
  printf("Division: %d\n", x/y);
  printf("Remainder: %d\n", x%y);
  ++z;
  printf("Increament: %d\n", z);
  --z;
  printf("Decreament: %d\n", z);
return 0;
}

